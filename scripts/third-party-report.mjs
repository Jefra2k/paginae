#!/usr/bin/env node
// Regenerates docs/THIRD-PARTY.md from `cargo metadata` and license-checker-rseidelsohn.
// Run with `npm run licenses:report`; commit the result.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const maxBuffer = 256 * 1024 * 1024;

// Fixed rows: PDFium and its prebuilt libraries are not Cargo or npm packages.
const FIXED = [
  ["PDFium", "chromium/8165", "BSD-3-Clause", "PDF engine (Google, Foxit); licences of its bundled parts in `resources/pdfium/licenses`", "shipped"],
  ["pdfium-binaries", "chromium/8165", "MIT", "Prebuilt PDFium libraries for Windows and macOS (bblanchon)", "shipped"],
];

const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], { cwd: root, encoding: "utf8", maxBuffer }),
);
const members = new Set(meta.workspace_members);
const rust = new Map();
for (const p of meta.packages) {
  if (members.has(p.id)) continue;
  rust.set(`${p.name}@${p.version}`, [p.name, p.version, p.license ?? "(none declared)", "Rust crate", "shipped"]);
}

const bin = join(root, "node_modules", "license-checker-rseidelsohn", "bin", "license-checker-rseidelsohn.js");
const npm = JSON.parse(
  execFileSync(process.execPath, [bin, "--production", "--json", "--excludePrivatePackages"], { cwd: root, encoding: "utf8", maxBuffer }),
);
const node = [];
for (const [key, info] of Object.entries(npm)) {
  const at = key.lastIndexOf("@");
  const lic = Array.isArray(info.licenses) ? info.licenses.join(" AND ") : String(info.licenses);
  node.push([key.slice(0, at), key.slice(at + 1), lic, "npm package (UI)", "shipped"]);
}

const byName = (a, b) => a[0].localeCompare(b[0], "en") || a[1].localeCompare(b[1], "en", { numeric: true });
const rows = [...FIXED, ...[...rust.values()].sort(byName), ...node.sort(byName)];
const esc = (v) => String(v).replace(/\|/g, "\|");

const out = [
  "# Third-party components",
  "",
  "Generated by `npm run licenses:report` (`scripts/third-party-report.mjs`) from `cargo metadata` and `license-checker-rseidelsohn --production`. Do not edit by hand. The Rust list is the full dependency graph of the Cargo workspace, including build-time, test-only and platform-specific crates (Linux, Android) that are not part of the Windows or macOS app; the npm list covers production dependencies only. Tools such as `cargo-deny`, WebdriverIO and `license-checker-rseidelsohn` are never shipped.",
  "",
  "| Component | Version | License | Use |",
  "|---|---|---|---|",
  ...rows.map(([n, v, l, u]) => `| ${esc(n)} | ${esc(v)} | ${esc(l)} | ${esc(u)} |`),
  "",
].join("\n");
writeFileSync(join(root, "docs", "THIRD-PARTY.md"), out);
console.log(`docs/THIRD-PARTY.md: ${rows.length} components (${rust.size} Rust, ${node.length} npm)`);
